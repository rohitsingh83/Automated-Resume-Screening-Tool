"""Build the GitHub Pages report: python scripts/build_site.py  -> docs/index.html"""

import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import pandas as pd
import plotly.express as px

from site_template import fig_html, page, table_html
from src.parser import pretty
from src.screener import load_jobs, screen_folder, to_dataframe

COLOURS = {"Shortlisted": "#22C55E", "Review": "#F59E0B", "Rejected": "#EF4444"}
TODAY = date(2026, 11, 21)


def main() -> None:
    jobs = load_jobs()
    sections, totals = [], {"Shortlisted": 0, "Review": 0, "Rejected": 0}
    for job in jobs.values():
        cands = screen_folder(job, ROOT / "resumes", today=TODAY)
        df = to_dataframe(cands)
        for k, v in df["Decision"].value_counts().items():
            totals[k] += v
        bar = px.bar(df.sort_values("Score"), x="Score", y="Candidate", color="Decision", orientation="h",
                     color_discrete_map=COLOURS, text="Score", category_orders={"Decision": list(COLOURS)},
                     title=f"Ranking for {job['title']}")
        bar.add_vline(65, line_dash="dash", line_color="#22C55E")
        bar.update_yaxes(categoryorder="total ascending", title=None)
        skills = job["must_have"] + job["nice_to_have"]
        grid = pd.DataFrame([[1 if s in c.parsed.skills else 0 for s in skills] for c in cands],
                            index=[c.parsed.name for c in cands], columns=[pretty(s) for s in skills])
        heat = px.imshow(grid, color_continuous_scale=[[0, "#7f1d1d"], [1, "#166534"]], aspect="auto",
                         title="Skill coverage (green = found)")
        heat.update_traces(text=grid.replace({1: "✓", 0: "✗"}).values, texttemplate="%{text}")
        heat.update_layout(coloraxis_showscale=False)
        table = df[["Rank", "Candidate", "Score", "Decision", "Must-have %", "Experience (yrs)", "Missing must-have",
                    "Flags"]]
        inner = (f'<div class="grid2">{fig_html(bar, 440)}{fig_html(heat, 440)}</div>'
                 f'<div class="scroll">{table_html(table)}</div>')
        sections.append((job["title"], f"{job['company']} · must-have: {', '.join(pretty(s) for s in job['must_have'])}"
                         f" · minimum {job['min_experience']} years", inner))

    sections.append(("How the score works", "Five explainable components, weights adjustable in the dashboard.",
                     table_html(pd.DataFrame({
                         "Component": ["Must-have skills", "Content similarity (TF-IDF cosine)", "Experience",
                                       "Nice-to-have skills", "Education"],
                         "Weight": ["40%", "25%", "15%", "15%", "5%"],
                         "Measured as": ["required skills found / required", "resume vs job description, rescaled",
                                         "years / required years", "bonus skills found / bonus skills",
                                         "meets degree level"]}))
                     + "<p>Shortlisted = score ≥ 65 and ≥ 80% must-have skills. Keyword-stuffed resumes lose 15 points "
                       "and are never auto-shortlisted. Emails and phone numbers are removed before scoring.</p>"))
    html = page(
        title="Automated Resume Screening Tool",
        tagline="An ATS-style screener that reads PDF, DOCX and TXT resumes, ranks candidates against a job "
                "description with TF-IDF + rules, and explains every decision.",
        accent="#38BDF8", repo="Automated-Resume-Screening-Tool",
        kpis=[("Resumes screened", "10"), ("Job descriptions", str(len(jobs))), ("Shortlisted (all jobs)",
              str(totals["Shortlisted"])), ("Skills in dictionary", "45"), ("Automated tests", "11")],
        sections=sections,
        note="All resumes are fictional, generated by scripts/create_sample_resumes.py.",
        run_cmds=["pip install -r requirements.txt", "python main.py --job data_analyst", "streamlit run app.py",
                  "uvicorn api:app --reload"])
    out = ROOT / "docs" / "index.html"
    out.write_text(html, encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(html) // 1024} KB)")


if __name__ == "__main__":
    main()
